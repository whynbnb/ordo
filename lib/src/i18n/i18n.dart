/// 轻量本地化：以中文原文为 key 查英文词典。
///
/// - 中文模式直接返回原文；
/// - 英文模式查 [enTranslations]，缺失时回退原文；
/// - 插值以 `{name}` 占位，由 [tr] 的第二个参数替换。
///
/// Rust 侧的用户可见错误由 [trError] 在边界处映射。
library;

import 'locale_store.dart';

String tr(String key, [Map<String, Object?>? args]) {
  var text = LocaleStore.instance.isEnglish
      ? (enTranslations[key] ?? key)
      : key;
  if (args != null && args.isNotEmpty) {
    args.forEach((name, value) {
      text = text.replaceAll('{$name}', '$value');
    });
  }
  return text;
}

/// 翻译 Rust 返回的错误信息（英文模式）。
String trError(String message) {
  if (message.isEmpty || !LocaleStore.instance.isEnglish) return message;
  final exact = enErrorMessages[message];
  if (exact != null) return exact;
  for (final entry in enErrorPrefixes) {
    if (message.startsWith(entry.$1)) {
      return entry.$2 + message.substring(entry.$1.length);
    }
  }
  return message;
}

